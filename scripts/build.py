#!/usr/bin/env python3
"""
NLAMS build tool — bundles the tree-structured source into ONE complete,
dependency-free HTML file: dist/index.html (offline demo / submission).

Usage:  python3 tools/build.py        (from anywhere; paths are resolved
                                       relative to the project root)
"""
import base64, glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def read(rel):
    return open(os.path.join(ROOT, rel)).read()

# 1. CSS — inline, with the login background swapped to an embedded data-URI
css = read('frontend/src/css/styles.css')
bg = base64.b64encode(open(os.path.join(ROOT, 'frontend/src/assets/bg.jpg'), 'rb').read()).decode()
css = css.replace("url('../assets/bg.jpg')", f"url('data:image/jpeg;base64,{bg}')")

# 2. JS modules — inline in load order; emblem swapped to embedded data-URI
emblem = base64.b64encode(open(os.path.join(ROOT, 'frontend/src/assets/emblem.png'), 'rb').read()).decode()
scripts = []
for path in sorted(glob.glob(os.path.join(ROOT, 'frontend/src/js', '*.js'))):
    js = open(path).read()
    js = js.replace("const EMBLEM='assets/emblem.png';",
                    f"const EMBLEM='data:image/png;base64,{emblem}';")
    scripts.append(f'<script>\n{js}\n</script>')

html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>NLAMS · Telangana — Land Acquisition & Management System</title>
<!-- NLAMS single-file build (generated by tools/build.py) — works offline, no server needed -->
<style>
{css}
</style>
</head>
<body>
<div id="app"></div>
<div id="toasts"></div>
{chr(10).join(scripts)}
</body>
</html>
"""

out = os.path.join(ROOT, 'dist', 'index.html')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write(html)

leftover = re.findall(r'assets/(?:emblem|bg)|\.\./assets', html)
print(f'dist/index.html written: {len(html)//1024} KB · modules bundled: {len(scripts)} · leftover asset refs: {len(leftover)}')
